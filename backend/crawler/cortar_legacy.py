def to_standard_cortar(cortar_no: str | None) -> str | None:
    """레거시 12-프리픽스 법정동코드를 표준 코드로 바꾼다.

    매핑에 없으면 **원본을 그대로** 돌려준다 — 12 코드가 아닌 전국 나머지 지역은
    이 함수를 그냥 통과하고, 매핑에 없는 12 코드도 기존 동작(0건)을 유지할 뿐
    새로 깨지지는 않는다.

    ⚠ 2026 개편 신코드는 여기서 번역하지 **않는다** — 이 함수는 V-WORLD 와 국토부
    실거래가가 **공유**하는데, 개편 건은 두 API 의 요구가 정반대라서다.
    공시가격 경로는 `to_vworld_cortar` 를 쓴다.

    Args:
        cortar_no: 법정동코드 10자리. None 이면 None 을 돌려준다.

    Returns:
        번역된 표준 코드, 또는 원본 그대로.
    """
    if not cortar_no:
        return cortar_no
    return LEGACY_CORTAR_MAP.get(cortar_no, cortar_no)


def to_vworld_cortar(cortar_no: str | None) -> str | None:
    """V-WORLD 공시가격 조회용 법정동코드로 바꾼다 (공시가격 경로 전용).

    두 단계를 순서대로 적용한다:
      1. 광주·전남 12-프리픽스 번역 (`to_standard_cortar` 와 동일)
      2. 2026 행정구역 개편 신코드 → 폐지된 옛 코드

    두 맵은 대상 지역이 겹치지 않으므로(12 프리픽스 vs 인천 28·경기 41) 순서가
    결과를 바꾸지 않지만, 장래에 겹치는 사례가 생기면 1 → 2 순서가 맞다.

    ⚠ 국토교통부 실거래가에는 쓰지 말 것 — 개편 건은 국토부가 **신 코드**를 받고
    옛 코드가 0건이라, 여기서 번역하면 되던 수집이 죽는다(모듈 docstring §2).

    Args:
        cortar_no: 법정동코드 10자리. None 이면 None 을 돌려준다.

    Returns:
        번역된 코드, 또는 원본 그대로(매핑 없음 = 기존 동작 유지).
    """
    if not cortar_no:
        return cortar_no
    # 1단계는 반드시 to_standard_cortar 를 **호출**한다 — dict.get 을 인라인으로 베끼면
    # 그쪽 동작이 바뀔 때 여기만 옛 동작으로 남는 드리프트 표면이 생긴다.
    code = to_standard_cortar(cortar_no)
    return VWORLD_REFORM_CORTAR_MAP.get(code, code)
